import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import type { MasarServer } from '@masar/core/server'

export const SERVER_ENTRY = '/.masar/server.ts'

/** The app root: the nearest folder (from cwd up) that has src/modules. */
export function findRoot(from = process.cwd()): string {
  let dir = resolve(from)
  while (true) {
    if (existsSync(join(dir, 'src', 'modules'))) return dir
    const parent = dirname(dir)
    if (parent === dir) {
      throw Object.assign(new Error('This is not a Masar app (no src/modules folder found)'), {
        hint: 'Run masar inside your app folder, or create one with: npm create masar@latest',
      })
    }
    dir = parent
  }
}

export function loadEnv(root: string) {
  const file = join(root, '.env')
  if (existsSync(file)) process.loadEnvFile(file)
}

function write(file: string, content: string) {
  mkdirSync(dirname(file), { recursive: true })
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return
  writeFileSync(file, content)
}

const HEADER = '// Generated by Masar. Do not edit: it is rewritten on every dev/build.\n'

/** Write the entry files Vite builds from. Modules are discovered by glob, so these rarely change. */
export function writeEntries(root: string) {
  write(
    join(root, '.masar/server.ts'),
    `${HEADER}import { createServer } from '@masar/core/server'
import app from '../src/config/app'
import database from '../src/config/database'

export default createServer({
  app,
  database,
  mode: import.meta.env.PROD ? 'production' : 'development',
  modules: import.meta.glob('../src/modules/*/module.ts', { eager: true }),
  schemas: import.meta.glob('../src/modules/*/schema.ts', { eager: true }),
  actions: import.meta.glob('../src/modules/*/actions.ts', { eager: true }),
  routes: import.meta.glob('../src/modules/*/routes.ts', { eager: true }),
  pages: import.meta.glob('../src/modules/*/views/pages/**/*.tsx', { eager: true }),
  migrations: import.meta.glob('../src/modules/*/migrations/*.ts', { eager: true }),
  locales: import.meta.glob('../src/locales/*.json', { eager: true }),
  storage: import.meta.glob('../src/config/storage.ts', { eager: true }),
  adminResources: import.meta.glob('../src/modules/admin/resources/*.ts', { eager: true }),
  adminDashboard: import.meta.glob('../src/modules/admin/dashboard.ts', { eager: true }),
  seeds: import.meta.glob('../src/modules/*/seeds.ts', { eager: true }),
  jobs: import.meta.glob('../src/modules/*/jobs/*.ts', { eager: true }),
  schedules: import.meta.glob('../src/modules/*/schedule.ts', { eager: true }),
  queue: import.meta.glob('../src/config/queue.ts', { eager: true }),
  mail: import.meta.glob('../src/config/mail.ts', { eager: true }),
  layouts: import.meta.glob('../src/shared/layouts/AppLayout.tsx', { eager: true }),
  moduleLayouts: import.meta.glob('../src/modules/*/views/layout.tsx'),
})
`,
  )
  const css = existsSync(join(root, 'src/shared/styles/app.css')) ? "import '../src/shared/styles/app.css'\n" : ''
  write(
    join(root, '.masar/client.tsx'),
    `${HEADER}${css}import { createMasarClient } from '@masar/core/client'

createMasarClient({
  pages: import.meta.glob('../src/modules/*/views/pages/**/*.tsx'),
  layouts: import.meta.glob('../src/shared/layouts/AppLayout.tsx', { eager: true }),
  moduleLayouts: import.meta.glob('../src/modules/*/views/layout.tsx'),
})
`,
  )
}

/** .masar/routes.gen.ts: every route of the app, with a typed path union. */
export function writeRoutes(root: string, app: MasarServer) {
  const rows = app.routes
    .map((r) => `  { method: '${r.method}', path: '${r.path}', kind: '${r.kind}', module: '${r.module}', target: '${r.target}' },`)
    .join('\n')
  write(
    join(root, '.masar/routes.gen.ts'),
    `${HEADER}// See them in the terminal with: masar routes

export const routes = [
${rows}
] as const

export type RoutePath = (typeof routes)[number]['path']
`,
  )
}
